# -*- coding: utf-8 -*-
"""Генератор инструкций по шитью для новичка.

Инструкция собирается из блоков:
  ('h', заголовок)          — заголовок раздела
  ('p', текст)              — абзац
  ('step', номер, заголовок, текст) — шаг
  ('tip', текст)            — совет
  ('warn', текст)           — важное предупреждение

Тексты подстраиваются под тип швейной машины (core.sewing).
"""
from __future__ import annotations

from typing import Dict, List, Tuple

from .models import ModelDef
from .piece import DraftResult
from .sewing import (MachineProfile, binding_steps, elastic_steps,
                     fabric_warning, get_machine, hem_steps, join_steps,
                     neck_rib_steps)

Block = Tuple[str, ...]


def build_instructions(model: ModelDef, meas: Dict[str, float],
                       params: Dict[str, object], machine_key: str,
                       draft: DraftResult) -> List[Tuple[str, List[Block]]]:
    profile = get_machine(machine_key)
    knit = model.draft_type in ("briefs", "tank", "tee")

    sections = []  # type: List[Tuple[str, List[Block]]]

    # ================== введение ==================
    intro = [
        ("p", "Эта инструкция рассчитана на человека, который шьёт впервые. "
              "Не пугайтесь количества шагов — каждый шаг простой, а «длинный» "
              "текст просто подробно объясняет, что и зачем делать."),
        ("p", "Ваша швейная машина: %s (%s). Все рекомендации ниже подобраны "
              "именно под неё." % (profile.title, profile.summary())),
    ]
    warn = fabric_warning(knit, profile)
    if warn:
        intro.append(("warn", warn))
    sections.append(("Перед началом", intro))

    # ================== словарик ==================
    glossary = [
        ("h", "Мини-словарик швейных терминов"),
        ("p", "Припуск — полоска ткани за линией шва (на выкройке это расстояние "
              "между сплошной линией кроя и пунктирной линией шва)."),
        ("p", "Стачать — соединить две детали машинной строчкой."),
        ("p", "Сметать — временно соединить детали крупными ручными стежками, "
              "чтобы ничего не съехало под лапкой машины. После стачивания нитки "
              "сметывания удаляют."),
        ("p", "Обметать — обработать срез ткани, чтобы он не осыпался "
              "(зигзагом, оверлоком или бельевым швом)."),
        ("p", "Заутюжить — прогладить припуск утюгом в одну сторону. "
              "Разутюжить — прогладить припуски в разные стороны."),
        ("p", "Долевая — направление нитей основы ткани. На выкройке оно показано "
              "двойной стрелкой. Если кроить не по долевой, вещь может перекоситься "
              "после стирки."),
        ("p", "Лицевая сторона — «красивая» сторона ткани. Изнаночная — изнанка."),
        ("p", "Проутюжильник — кусок х/б ткани или марли, через который утюжат, "
              "чтобы не оставить лассы (следы утюга)."),
    ]
    sections.append((None, glossary))

    # ================== материалы ==================
    mat_blocks = [("h", "Что понадобится")]
    mat_blocks.append(("p", "Ткань: %s Ширина ткани 150 см, нужно примерно %.0f см."
                       % (model.fabric_hint, draft.fabric[1])))
    if knit:
        mat_blocks.append(("p", "Для этой модели нужен трикотаж — ткань, которая "
                              "тянется. Для первого раза отлично подходит кулирка "
                              "или интерлок плотностью 180-220 г/м²."))
    for name, length in draft.elastic:
        mat_blocks.append(("p", "%s — примерно %.0f см." % (name, length)))
    mat_blocks.append(("p", "Инструменты: швейная машина, нитки полиэстер № 40 "
                           "(по цвету ткани + немного контрастных для смётывания), "
                           "игла для трикотажа Jersey № 70-80, портновские ножницы, "
                           "булавки с шариками, сантиметровая лента, мел или обмылок, "
                           "утюг с проутюжильником."))
    sections.append(("Материалы и инструменты", mat_blocks))

    # ================== подготовка ткани ==================
    prep = [
        ("h", "Подготовка ткани"),
        ("p", "1. Стирка (декатировка). Постирайте и высушите ткань так, как будете "
              "стирать готовую вещь. Ткань может дать усадку — лучше, чтобы это "
              "случилось до раскроя, а не после."),
        ("p", "2. Утюжка. Отутюжьте ткань с паром, дайте остыть. Складки на ткани — "
              "причина перекосов при раскрое."),
    ]
    sections.append((None, prep))

    # ================== раскрой ==================
    cut_blocks = [("h", "Раскрой")]
    cut_blocks.append(("p", "1. Расстелите ткань на большом столе в один слой "
                       "(для деталей на сгибе — в два слоя, лицевыми сторонами внутрь, "
                       "совместив кромки)."))
    cut_blocks.append(("p", "2. Распечатайте выкройку в масштабе 100% (кнопка "
                       "«Реальный размер» в настройках печати PDF). Проверьте "
                       "контрольный квадрат 10 x 10 см на первом листе линейкой. "
                       "Склейте листы по меткам совмещения и обрежьте поля."))
    cut_blocks.append(("p", "3. Разложите детали: линии «СГИБ» — на сгиб ткани, "
                       "двойная стрелка (долевая) — вдоль кромки ткани. "
                       "Приколите выкройки булавками."))
    cut_blocks.append(("p", "4. Обведите выкройки мелом. Перенесите на ткань метки "
                       "(короткие поперечные черточки) и линию сгиба."))
    cut_blocks.append(("p", "5. Вырезайте детали по СПЛОШНОЙ линии (линия кроя). "
                       "Пунктирная линия — линия шва, по ней будете шить. "
                       "Не забывайте про «зубчики»-метки на боковых швах."))
    for piece in draft.pieces:
        cut_blocks.append(("p", "Деталь «%s» — %s (%s)."
                           % (piece.name, piece.cut_note, piece.size_text())))
    sections.append((None, cut_blocks))

    # ================== пошаговый пошив ==================
    builder = _BUILDERS.get(model.draft_type)
    if builder:
        sections.extend(builder(model, meas, params, profile, draft))

    # ================== проверка ==================
    check = [
        ("h", "Проверка и примерка"),
        ("p", "Выверните изделие на лицевую сторону, встряхните и оцените: "
              "нет ли перекосов швов, сборок, «волн» по краям."),
        ("p", "Примерьте. Если тесно — не страшно: по боковым швам припуски можно "
              "расширить на 0,5-1 см и прошить заново (для этого мы и оставляли запас)."),
        ("p", "Финальная утюжка: прогладьте изделие через проутюжильник, "
              "особенно тщательно — швы."),
        ("tip", "Первую вещь шейте из недорогой ткани (старая простыня, дешёвая "
                "кулирка). Вторая получится заметно лучше первой — это нормально!"),
    ]
    sections.append(("Финал", check))

    # ================== контрольные длины ==================
    chk = [("h", "Контрольные длины (по линии шва)")]
    for name, val in draft.checks:
        chk.append(("p", "%s — %.1f см." % (name, val)))
    chk.append(("p", "Сверьте длины срезов перед стачиванием: у совмещаемых "
                     "деталей они должны совпадать или отличаться не более чем "
                     "на 0,5 см."))
    sections.append((None, chk))

    # ================== советы по машине ==================
    tips = [("h", "Советы по вашей машине")]
    if profile.key == "straight":
        tips.append(("p", "Прямострочная машина требует аккуратности с трикотажем: "
                          "игла Jersey, стежок 2 мм, никакой растяжки ткани. "
                          "Все швы в инструкции даны бельевым (французским) способом — "
                          "они прочные и не осыпаются."))
    elif profile.key == "zigzag":
        tips.append(("p", "На бытовой машине главный друг новичка — зигзаг: "
                          "им обметывают срезы и подшивают трикотаж. Купите двойную "
                          "иглу 2,5/70 — подшивка станет фабрично-аккуратной."))
    elif profile.key == "overlock":
        tips.append(("p", "Оверлоком обметывайте срезы ПОСЛЕ стачивания на машине. "
                          "4-ниточный стежок прочнее, 3-ниточный эластичнее — "
                          "для трикотажа лучше 3-ниточный или 4-ниточный с дифференциальной "
                          "подачей (растяжение исключит «волны»)."))
    else:
        tips.append(("p", "Распошивалка (плоский шов) — для подгибки низа и рукавов. "
                          "Стачивайте на обычной машине, обметывайте оверлоком, "
                          "подшивайте распошивалкой: это фабричный цикл."))
    tips.append(("p", "Перед шитьём на реальной детали сделайте пробную строчку "
                      "на лоскутке той же ткани с теми же нитками."))
    sections.append((None, tips))

    return sections


# ==================== пошаговый пошив: конкретные модели ====================

def _sew_briefs(model, meas, params, profile, draft):
    knit = True
    blocks = [("h", "Пошив трусов-слипов (пошагово)")]
    n = [0]

    def step(title, body):
        n[0] += 1
        blocks.append(("step", n[0], title, body))

    for t, b in join_steps(profile, "боковой", knit):
        step("Боковые швы: " + t,
             b + "\nСкладывайте ПЕРЕДНЕЕ и ЗАДНЕЕ полотнища лицевыми сторонами "
                 "внутрь, совмещая боковые срезы и метки «линия бёдер». "
                 "Выполните оба боковых шва.")
    step("Средний шов (ластовица)",
         "Сложите полотнища лицевыми сторонами внутрь, уравняйте нижние средние "
         "срезы (у точек ластовицы есть насечки). Стачайте средние срезы переда "
         "и зада одной строчкой и обработайте срез выбранным способом "
         "(см. шаг 1). Разутюжьте.")
    for t, b in elastic_steps(profile, "вырез ноги",
                              draft.elastic[1][1] if len(draft.elastic) > 1 else 80.0):
        step("Вырез ноги №1: " + t, b + "\nПовторите для второго выреза ноги.")
    for t, b in elastic_steps(profile, "пояс", draft.elastic[0][1] if draft.elastic else 70.0):
        step("Пояс: " + t, b)
    step("Финальная утюжка",
         "Выверните трусы на лицевую сторону, расправьте резинку по краям и "
         "приутюжьте через проутюжильник, слегка оттягивая резинку.")
    return [("Пошив", blocks)]


def _sew_boxers(model, meas, params, profile, draft):
    knit = str(params.get("fabric", "woven")) != "woven"
    blocks = [("h", "Пошив трусов-боксёров (пошагово)")]
    n = [0]

    def step(title, body):
        n[0] += 1
        blocks.append(("step", n[0], title, body))

    for t, b in join_steps(profile, "боковой", knit):
        step("Боковые швы: " + t,
             b + "\nПередняя и задняя панели складываются лицевыми сторонами "
                 "внутрь; боковые срезы — от верхнего края до метки у низа штанины. "
                 "Выполните оба шва.")
    for t, b in join_steps(profile, "шаговый", knit):
        step("Шаговые швы: " + t,
             b + "\nСложите перед и зад лицевыми сторонами внутрь и стачайте "
                 "кривые шаговые срезы от низа штанины до точки ластовицы. "
                 "Следите, чтобы строчка шла плавно по кривой — не «спрямляйте» её.")
    step("Средний шов",
         "Совместите нижние средние срезы переда и зада (насечки у точек "
         "ластовицы должны совпасть) и стачайте их короткой строчкой. "
         "Обработайте срез. Разутюжьте.")
    if knit:
        for t, b in elastic_steps(profile, "пояс", draft.elastic[0][1] if draft.elastic else 95.0):
            step("Пояс: " + t, b)
    else:
        step("Кулиска под резинку",
             "1. Подогните верхний край на 0,7 см на изнанку и заутюжьте (это "
             "скрытый край). 2. Подогните ещё раз на ширину резинки + 0,7 см, "
             "приметайте. 3. Проложите строчку по нижнему краю кулиски, оставив "
             "открытым участок 3 см для вдевания резинки. 4. Вденьте резинку "
             "(длина — по талии минус 10%), заколите концы и застрочите участок.")
    for t, b in hem_steps(profile, 2.0):
        step("Низ штанин: " + t,
             b + "\nПовторите для второй штанины. Проверьте, что длина штанин "
                 "одинаковая.")
    step("Финальная утюжка",
         "Выверните боксёры, расправьте швы и приутюжьте через проутюжильник.")
    return [("Пошив", blocks)]


def _sew_tank(model, meas, params, profile, draft):
    knit = True
    blocks = [("h", "Пошив майки (пошагово)")]
    n = [0]

    def step(title, body):
        n[0] += 1
        blocks.append(("step", n[0], title, body))

    for t, b in join_steps(profile, "плечевой", knit):
        step("Плечевые швы (бретели): " + t,
             b + "\nСложите полочку и спинку лицевыми сторонами внутрь и стачайте "
                 "короткие плечевые края бретелей. Швы маленькие — будьте внимательны, "
                 "не застрочите лишнее.")
    for t, b in binding_steps(profile, knit):
        step("Горловина: " + t,
             b + "\nНачинайте и заканчивайте окантовку на 2 см в сторону плечевого "
                 "шва от середины спинки, чтобы шов бейки не попал на самое видное место.")
    for t, b in binding_steps(profile, knit):
        step("Проймы: " + t, b + "\nПовторите для второй проймы.")
    for t, b in join_steps(profile, "боковой", knit):
        step("Боковые швы: " + t,
             b + "\nСтачайте полочку и спинку по боковым срезам от нижней точки "
                 "проймы до низа, начиная и заканчивая строчку закрепками.")
    for t, b in hem_steps(profile, 2.0):
        step("Низ майки: " + t, b)
    step("Финальная утюжка",
         "Выверните майку, расправьте окантовку и подгибку, приутюжьте "
         "через проутюжильник.")
    return [("Пошив", blocks)]


def _sew_tee(model, meas, params, profile, draft):
    knit = True
    blocks = [("h", "Пошив футболки (пошагово)")]
    n = [0]

    def step(title, body):
        n[0] += 1
        blocks.append(("step", n[0], title, body))

    for t, b in join_steps(profile, "плечевой", knit):
        step("Плечевые швы: " + t,
             b + "\nСложите полочку и спинку лицевыми сторонами внутрь, стачайте "
                 "плечевые срезы от горловины к плечевой точке.")
    rib_len = draft.elastic[0][1] if draft.elastic else 50.0
    for t, b in neck_rib_steps(profile, rib_len):
        step("Горловина: " + t, b)
    step("Подготовка рукавов",
         "Сложите каждый рукав вдоль лицевой стороной внутрь — середина оката "
         "(верхняя стрелка) должна смотреть к плечевому шву. Времени это не займёт: "
         "просто убедитесь, что вырезаете 2 зеркальные детали (выкройка симметрична).")
    for t, b in join_steps(profile, "рукав", knit):
        step("Втачать рукава: " + t,
             b + "\nВтачивайте рукав в ОТКРЫТУЮ пройму (боковые швы ещё не сшиты): "
                 "совместите метку середины оката с плечевым швом, концы оката — "
                 "с краями проймы. Припосаживайте окат пальцами, если он длиннее "
                 "проймы на 0,5-1 см — это нормально.")
    for t, b in join_steps(profile, "боковой", knit):
        step("Боковые швы и швы рукавов: " + t,
             b + "\nОдной строчкой от нижнего края рукава через подмышку до низа "
                 "изделия. Начните и закончите закрепками, в области проймы "
                 "не растягивайте ткань.")
    for t, b in hem_steps(profile, 2.0):
        step("Низ рукавов: " + t, b + "\nПовторите для второго рукава.")
    for t, b in hem_steps(profile, 2.5):
        step("Низ футболки: " + t, b)
    step("Финальная утюжка",
         "Выверните футболку, приутюжьте горловину, подгибки и боковые швы "
         "через проутюжильник.")
    return [("Пошив", blocks)]


_BUILDERS = {
    "briefs": _sew_briefs,
    "boxers": _sew_boxers,
    "tank": _sew_tank,
    "tee": _sew_tee,
}


def instructions_to_text(sections) -> str:
    """Простое текстовое представление (для окна программы и .txt)."""
    lines = []
    step_no = 0
    for title, blocks in sections:
        if title:
            lines.append("")
            lines.append("=" * 60)
            lines.append(title.upper())
            lines.append("=" * 60)
        for b in blocks:
            if b[0] == "h":
                lines.append("")
                lines.append(b[1])
                lines.append("-" * len(b[1]))
            elif b[0] == "p":
                lines.append(b[1])
                lines.append("")
            elif b[0] == "step":
                step_no += 1
                lines.append("ШАГ %d. %s" % (b[1], b[2]))
                lines.append(b[3])
                lines.append("")
            elif b[0] == "tip":
                lines.append("СОВЕТ: " + b[1])
                lines.append("")
            elif b[0] == "warn":
                lines.append("ВАЖНО: " + b[1])
                lines.append("")
    return "\n".join(lines)
