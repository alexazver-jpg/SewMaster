def instructions_to_text(sections) -> str:
    """Простое текстовое представление (для окна программы и .txt)."""
    lines = []
    step_no = 0
    for title, blocks in sections:
        if title:
            lines.append("")
            lines.append("=" * 60)
            lines.append(title.upper())
            lines.append("=" * 60)
        for b in blocks:
            if b[0] == "h":
                lines.append("")
                lines.append(b[1])
                lines.append("-" * len(b[1]))
            elif b[0] == "p":
                lines.append(b[1])
                lines.append("")
            elif b[0] == "step":
                step_no += 1
                lines.append("ШАГ %d. %s" % (b[1], b[2]))
                lines.append(b[3])
                lines.append("")
            elif b[0] == "tip":
                lines.append("СОВЕТ: " + b[1])
                lines.append("")
            elif b[0] == "warn":
                lines.append("ВАЖНО: " + b[1])
                lines.append("")
    return "\n".join(lines)
