# -*- coding: utf-8 -*-
"""Выкройка: юбка-солнце на резинке (для новичка).

Классическое «солнце» — полный круг (360 градусов). Деталь — четверть
кольца, которая кроится на сгибе по средней линии: в развёрнутом виде
получается полукруг (переднее или заднее полотнище). Два полотнища =
полный круг.

Пояс — кулиска с резинкой, поэтому кольцо пояса строится по обхвату
бёдер (юбка должна проходить через бёдра при надевании).

Все размеры — в сантиметрах. Ось Y направлена вниз.
Сегменты контура:
  0 — дуга пояса (внутренний радиус r), 1 — боковой срез (прямой),
  2 — дуга низа (внешний радиус R),      3 — средняя линия (СГИБ, припуск 0).
"""
from __future__ import annotations

import math
from typing import Dict

from ..geom import Contour, Pt, dist
from ..piece import (DraftResult, Notch, PatternPiece, PieceLabel, SeamInfo)

# Множитель для кубических Безье, приближающих четверть окружности
K = 0.5523


def build(m: Dict[str, float], p: Dict[str, object]) -> DraftResult:
    hips = float(m["hips"])
    waist = float(m["waist"])
    length = float(m["length"])

    ease = float(p.get("ease", 4.0))
    allow = float(p.get("allowance", 1.0))
    elastic_w = float(p.get("elastic_w", 3.0))

    # Кольцо пояса должно проходить через бёдра: минимум бёдра + 2 см.
    waist_open = hips + max(ease, 2.0)
    r = waist_open / (2.0 * math.pi)          # радиус линии пояса
    R = r + length                            # радиус линии низа

    # ---------------- деталь: четверть кольца ---------------------------
    # A = верх средней линии (на дуге пояса), ориентация: сгиб слева (x=0),
    # боковой срез сверху (y=0), дуга пояса у начала координат.
    A = (0.0, r)
    P1 = (r, 0.0)                             # конец дуги пояса (боковой срез)
    P2 = (R, 0.0)                             # боковой срез: от пояса к низу
    P3 = (0.0, R)                             # конец дуги низа на сгибе

    c = Contour(A)
    c.cubic((K * r, r), (r, K * r), P1)       # дуга пояса (90 градусов)
    c.line(P2)                                # боковой срез (долевая!)
    c.cubic((R, K * R), (K * R, R), P3)       # дуга низа (90 градусов)
    c.line(A)                                 # средняя линия (сгиб)

    piece = PatternPiece(
        "panel", "ПОЛОТНИЩЕ ЮБКИ", c,
        "2 детали со сгибом (переднее и заднее полотнища; "
        "сгиб — по средней линии)")
    piece.allowance = allow
    piece.allowance_edges = [allow, allow, allow, 0.0]
    piece.folds = [((0.0, r + 3.0), (0.0, R - 3.0))]
    # долевая — вдоль сгиба (вертикально), внутри детали
    gx = (r + R) / 2.0
    gy1 = 3.0
    gy2 = math.sqrt(max(R * R - gx * gx, 1.0)) - 3.0
    piece.grain = ((gx, gy1), (gx, gy2))
    piece.notches = [
        Notch((gx, 0.0), 90.0, "середина бокового среза"),
        Notch((r * 0.7071, r * 0.7071), 45.0, "середина дуги пояса"),
    ]
    mid_rad = (r + R) / 2.0 * 0.7071
    piece.labels = [
        PieceLabel((mid_rad, mid_rad),
                   ["ЮБКА-СОЛНЦЕ", "кроить 2 со сгибом", "(перед и зад)"],
                   bold=True),
    ]

    # ---------------- контрольные длины ---------------------------------
    g = piece.contour.seg_groups(48)

    def glen(idx):
        seg = g[idx]
        return sum(dist(seg[j], seg[j + 1]) for j in range(len(seg) - 1))

    waist_arc = glen(0)
    hem_arc = glen(2)
    side_edge = glen(1)

    checks = [
        ("Радиус линии пояса", r),
        ("Радиус линии низа", R),
        ("Дуга пояса одного полотнища", waist_arc),
        ("Дуга низа одного полотнища", hem_arc),
        ("Боковой срез (перед = зад)", side_edge),
        ("Обхват пояса всего кольца (2 полотнища)", 2.0 * 2.0 * waist_arc),
        ("Длина юбки по середине", length),
    ]

    seams = [
        SeamInfo("side", "Боковые швы", "side", side_edge,
                 "Стачать переднее и заднее полотнища по боковым срезам (2 шва)."),
        SeamInfo("waist_casing", "Кулиска под резинку", "elastic", 0.0,
                 "Подогнуть верхний край и выполнить кулиску, вдеть резинку."),
        SeamInfo("hem", "Подшивка низа", "hem", 0.0,
                 "Обработать нижний срез (дуга по косой — подшивать узко)."),
    ]

    # ---------------- материалы ------------------------------------------
    waist_elastic = waist * 0.9 + 4.0
    elastic = [
        ("Резинка для кулиски, ширина %g см" % elastic_w,
         round(waist_elastic + 2.0, 1)),
    ]

    # Расход: каждое полотнище — квадрат со стороной ~R + припуски,
    # полотнища кроятся со сгибом. Плюс запас на кулиску.
    fabric_len = 2.0 * (R + 2.0 * allow + 6.0)
    fabric = (150.0, round(fabric_len, 1))

    notes = [
        "Ткани с плотным плетением и мягким падением: габардин, сатин, "
        "вискоза, лёгкий футер. Тянущийся трикотаж тоже подходит.",
        "Полный круг пояса равен «бёдра + прибавка» — юбка надевается "
        "через бёдра без застёжки, пояс собирается на резинку.",
    ]
    if 2.0 * R > 145.0:
        notes.append(
            "Внимание: диаметр круга %.0f см не помещается по ширине ткани "
            "150 см. Кроите каждое полотнище из двух четвертей (тогда "
            "боковых швов будет 4) — качество юбки от этого не пострадает."
            % (2.0 * R,))

    return DraftResult([piece], checks, seams, fabric, elastic, notes)
