# -*- coding: utf-8 -*-
"""Выкройка: наволочка с запахом («с ушками») для подушки.

Классика домашнего постельного белья: одно цельное полотнище, которое
подшивается по двум коротким краям (края входа), складывается с нахлёстом
(запахом) и стачивается двумя боковыми швами. Молния и пуговицы не нужны —
это простейший проект для первого шитья.

Геометрия (Y вниз, сантиметры):
  W — сторона подушки вдоль входа (обычно короткая),
  L — вторая сторона подушки,
  sa — припуск боковых швов,
  hem — подгибка коротких краёв (двойная 1+1 см),
  F1 = F2 = (L + overlap) / 2 — высота верхнего/нижнего клапанов запаха,
  T = 2*hem + 2*L + overlap — полная длина полотнища в крое.

Линия шва (пунктир на выкройке) — «рамка готовой наволочки» W x L:
её БОКОВЫЕ стороны — настоящие линии швов, ВЕРХ/НИЗ — линии сгиба
(по ним подворачиваются клапаны). Всё ткань за рамкой: сверху/снизу —
клапаны запаха с подгибкой, слева/справа — припуски боковых швов.

Сегменты контура: 0 — верх (ЛИНИЯ СГИБА), 1 — правый (боковой шов),
2 — низ (ЛИНИЯ СГИБА), 3 — левый (боковой шов).
"""
from __future__ import annotations

from typing import Dict

from ..geom import Contour
from ..piece import (DraftResult, Notch, PatternPiece, PieceLabel, SeamInfo)

HEM = 2.0  # подгибка коротких краёв: двойная 1 + 1 см


def build(m: Dict[str, float], p: Dict[str, object]) -> DraftResult:
    W = float(m["pillow_w"])
    L = float(m["pillow_l"])
    overlap = float(p.get("overlap", 20.0))
    sa = float(p.get("allowance", 1.5))
    hem = HEM

    if overlap >= L:
        overlap = max(10.0, L * 0.5)   # запах не длиннее самой подушки

    # клапаны запаха — одинаковые, встречаются в середине спинки
    f1 = (L + overlap) / 2.0
    f2 = L + overlap - f1
    a_top = hem + f1                   # верхняя линия сгиба от верхнего края
    b_bot = hem + f2                   # нижняя линия сгиба от нижнего края
    total = a_top + L + b_bot          # длина полотнища в крое
    assert abs(f1 + f2 - (L + overlap)) < 1e-9
    assert abs(total - (2 * hem + 2 * L + overlap)) < 1e-9

    # ---------------- деталь: рамка готовой наволочки ----------------
    # (sa, a_top) — верхний левый угол; обход по часовой стрелке.
    c = Contour((sa, a_top))
    c.line((sa + W, a_top))            # 0: верх — линия сгиба
    c.line((sa + W, a_top + L))        # 1: правый — боковой шов
    c.line((sa, a_top + L))            # 2: низ — линия сгиба
    c.line((sa, a_top))                # 3: левый — боковой шов

    piece = PatternPiece(
        "body", "ПОЛОТНИЩЕ НАВОЛОЧКИ", c,
        "1 деталь (целое полотнище, без сгибов)")
    piece.fabric_note = "сатин / поплин / бязь"
    piece.allowance = sa
    piece.allowance_edges = [hem + f1, sa, hem + f2, sa]
    # долевая — вдоль длины полотнища (вертикально)
    gx = sa + W * 0.38
    piece.grain = ((gx, a_top + 3.0), (gx, a_top + L - 3.0))
    # насечки: линии сгиба выходят на боковые края
    piece.notches = [
        Notch((sa, a_top), 0.0, "верхняя линия сгиба"),
        Notch((sa, a_top + L), 0.0, "нижняя линия сгиба"),
        Notch((sa + W, a_top), 180.0, "верхняя линия сгиба"),
        Notch((sa + W, a_top + L), 180.0, "нижняя линия сгиба"),
    ]
    piece.labels = [
        PieceLabel((sa + W / 2.0, a_top / 2.0),
                   ["ВЕРХНИЙ КЛАПАН ЗАПАХА", "подогнуть вниз", "по линии сгиба"]),
        PieceLabel((sa + W / 2.0, a_top + L / 2.0),
                   ["НАВОЛОЧКА %g x %g" % (W, L), "лицевая сторона", "боковые швы — по пунктиру"],
                   bold=True),
        PieceLabel((sa + W / 2.0, a_top + L + b_bot / 2.0),
                   ["НИЖНИЙ КЛАПАН ЗАПАХА", "подогнуть вверх", "по линии сгиба"]),
    ]

    # самопроверка: крой должен быть точным прямоугольником
    x0, y0, x1, y1 = piece.bbox(True)
    assert abs((x1 - x0) - (W + 2 * sa)) < 0.02, "ширина кроя неверна"
    assert abs((y1 - y0) - total) < 0.02, "длина кроя неверна"

    # ---------------- контрольные длины ---------------------------------
    checks = [
        ("Ширина полотнища в крое", W + 2 * sa),
        ("Длина полотнища в крое", total),
        ("Верхняя линия сгиба (от верхнего края)", a_top),
        ("Нижняя линия сгиба (от нижнего края)", b_bot),
        ("Ширина готовой наволочки", W),
        ("Длина готовой наволочки", L),
        ("Запах (нахлёст клапанов)", overlap),
        ("Подгибка коротких краёв (с каждой стороны)", hem),
    ]

    seams = [
        SeamInfo("hem_edges", "Подгибка краёв запаха", "hem", 2.0 * W,
                 "Подшить оба коротких среза двойной подгибкой 1+1 см."),
        SeamInfo("side", "Боковые швы", "side", L,
                 "Стачать полотнище по боковым срезам от верхней до нижней "
                 "линии сгиба (2 шва)."),
    ]

    fabric = (150.0, round(total + 5.0, 1))

    notes = [
        "Полотнище — прямоугольник: при желании его можно начертить прямо "
        "на ткани линейкой по контрольным длинам (см. инструкцию). Печатная "
        "выкройка нужна для точной разметки линий сгиба запаха.",
        "Хлопковые ткани после первой стирки дают усадку до 3-5% — "
        "обязательно декатируйте ткань (постирайте и прогладьте до раскроя).",
        "Подушка входит плотно и не «гуляет», если запах не меньше 15 см. "
        "Для пуховых подушек увеличьте запах в параметрах.",
    ]

    return DraftResult([piece], checks, seams, fabric, [], notes)
