# -*- coding: utf-8 -*-
"""Профили швейных машин и подбор способов обработки швов.

Программа подстраивает инструкции под возможности машины пользователя:
если нет оверлока — предлагает зигзаг или бельевой (французский) шов,
если нет распошивалки — двойную иглу или зигзаг для подгибки.
"""
from __future__ import annotations

from typing import Dict, List, Tuple


class MachineProfile(object):
    def __init__(self, key: str, title: str, description: str,
                 zigzag: bool, overlock: bool, cover: bool, twin: bool):
        self.key = key
        self.title = title
        self.description = description
        self.zigzag = zigzag      # есть ли зигзаг / эластичная строчка
        self.overlock = overlock  # есть ли оверлок
        self.cover = cover        # есть ли распошивалка (плоский шов)
        self.twin = twin          # можно ли поставить двойную иглу

    def summary(self) -> str:
        feats = []
        feats.append("прямая строчка")
        if self.zigzag:
            feats.append("зигзаг")
        if self.twin:
            feats.append("двойная игла")
        if self.overlock:
            feats.append("оверлок")
        if self.cover:
            feats.append("плоский шов (распошивалка)")
        return ", ".join(feats)


MACHINES = {
    "straight": MachineProfile(
        "straight",
        "Прямострочная машина",
        "Старые или специализированные машины: только прямая строчка. "
        "Инструкции будут использовать бельевой (французский) шов и ручную обработку.",
        zigzag=False, overlock=False, cover=False, twin=False),
    "zigzag": MachineProfile(
        "zigzag",
        "Бытовая машина с зигзагом",
        "Обычная бытовая швейная машина: прямая строчка, зигзаг, петли. "
        "Срезы будем обметывать зигзагом, подшивать двойной иглой или зигзагом.",
        zigzag=True, overlock=False, cover=False, twin=True),
    "overlock": MachineProfile(
        "overlock",
        "Бытовая машина + оверлок",
        "У вас есть оверлок (краеобмёточная машина). Стачивать будем на машине, "
        "срезы обметывать оверлоком.",
        zigzag=True, overlock=True, cover=False, twin=True),
    "cover": MachineProfile(
        "cover",
        "Машина + оверлок + распошивалка",
        "Полный набор: стачная машина, оверлок и распошивалка (плоский шов). "
        "Подшивка будет как на фабричных футболках.",
        zigzag=True, overlock=True, cover=True, twin=True),
}

DEFAULT_MACHINE = "zigzag"


def get_machine(key: str) -> MachineProfile:
    return MACHINES.get(key) or MACHINES[DEFAULT_MACHINE]


# ==================== способы выполнения швов ====================

def join_steps(profile: MachineProfile, seam_title: str, knit: bool = True,
               stitch_cm: float = 1.0) -> List[Tuple[str, str]]:
    """Как стачать шов и обработать срезы. Возвращает [(заголовок, текст)]."""
    steps = []  # type: List[Tuple[str, str]]
    if profile.overlock:
        steps.append((
            "Стачать и обметать",
            "Сложите детали лицевыми сторонами внутрь, уравняйте срезы. "
            "Стачайте на швейной машине прямой строчкой по линии шва (пунктир на выкройке), "
            "длина стежка %s. Затем обметайте оба припуска вместе на оверлоке."
            % ("2,5 мм (трикотаж)" if knit else "2-2,5 мм")))
    elif profile.zigzag:
        steps.append((
            "Стачать прямой строчкой",
            "Сложите детали лицевыми сторонами внутрь, сколите булавками поперёк "
            "будущего шва (или сметайте). Стачайте прямой строчкой по линии шва, "
            "длина стежка 2,5 мм для трикотажа, 2-2,5 мм для ткани. "
            "Начало и конец строчки закрепите обратной строчкой."))
        steps.append((
            "Обметать срезы зигзагом",
            "Обрежьте припуски до 0,7-1 см. Обметайте оба припуска ВМЕСТЕ одним "
            "зигзагом (ширина stitch 4-5 мм, длина 2 мм). Припуски заутюжьте на одну "
            "сторону или разутюжьте вразутюжку."))
    else:
        steps.append((
            "Выполнить бельевой (французский) шов",
            "Прямострочной машине не нужен оверлок — используем самый прочный "
            "и аккуратный способ:\n"
            "1) Сложите детали ИЗНАНОЧНЫМИ сторонами внутрь (лицом к лицу НЕ надо!) "
            "и стачайте на расстоянии 0,4-0,5 см от срезов, длина стежка 2 мм.\n"
            "2) Обрежьте припуски близко к строчке — до 0,3 см.\n"
            "3) Выверните детали лицевыми сторонами внутрь, расправьте шов, "
            "приутюжьте и проложите вторую строчку на расстоянии 0,5-0,6 см от сгиба. "
            "Теперь все срезы спрятаны внутри шва."))
        if knit:
            steps.append((
                "Важно для трикотажа на прямой строчке",
                "Ставьте иглу с закруглённым остриём (маркировка Jersey/Stretch, № 70-80) "
                "и не растягивайте ткань под лапкой — обычная строчка не тянется, "
                "и если её растянуть, она лопнет. Длина стежка 2-2,5 мм."))
    return steps


def elastic_steps(profile: MachineProfile, edge_title: str,
                  elastic_len: float) -> List[Tuple[str, str]]:
    """Как пришить резинку к краю (вырез ноги / пояс)."""
    steps = []
    steps.append((
        "Подготовить резинку",
        "Отрежьте резинку длиной %.0f см. Сложите её в кольцо, перехлёст 1,5 см, "
        "стачайте концы прямой строчкой по квадрату — получится кольцо." % elastic_len))
    steps.append((
        "Разметить и сколоть",
        "Сложите кольцо резинки и край детали пополам, отметьте булавками "
        "4 одинаковые части (можно мелом). Совместите метки резинки с метками края."))
    if profile.zigzag or profile.overlock:
        steps.append((
            "Притачать резинку",
            "Приложите резинку к лицевой стороне края детали, край в край. "
            "Притачивайте ЗИГЗАГОМ по самому краю резинки, одновременно "
            "растягивая резинку между булавками до длины среза детали. "
            "Постепенно снимайте булавки. Не тяните ткань — только резинку."))
        steps.append((
            "Отогнуть и настрочить",
            "Отогните резинку на изнаночную сторону, аккуратно расправьте. "
            "Проложите вторую строчку зигзагом (или прямой, если машина справляется) "
            "по внутреннему краю резинки, снова слегка растягивая. "
            "Удалите намётку, приутюжьте через проутюжильник."))
    else:
        steps.append((
            "Втачать резинку прямой строчкой",
            "Прямострочной машиной: наложите резинку на лицевую сторону края, "
            "сколите по меткам. Проложите ДВЕ параллельные прямые строчки — по верхнему "
            "и нижнему краю резинки, — растягивая резинку равномерно между булавками. "
            "Длина стежка 2 мм. Распрямьте край: ткань должна собраться мягкими складками."))
        steps.append((
            "Закрепить край",
            "Отогните резинку внутрь и приутюжьте. По желанию прихватите внутренний "
            "край резинки ручными стежками в нескольких местах."))
    return steps


def hem_steps(profile: MachineProfile, hem_w: float = 2.0) -> List[Tuple[str, str]]:
    """Подшивка низа изделия/рукава."""
    if profile.cover:
        return [("Подшить распошивалкой",
                 "Подогните припуск %.0f см и заутюжьте. Подшейте распошивалкой "
                 "(плоский шов) с лицевой стороны на 1,5-2 см от сгиба — получится "
                 "аккуратная двойная строчка, как на готовых футболках." % hem_w)]
    if profile.twin:
        return [("Подшить двойной иглой",
                 "Установите двойную иглу 2,5/70 или 4/80. Подогните припуск %.0f см, "
                 "заутюжьте. Шейте с лицевой стороны на 1,5 см от сгиба: двойная игла "
                 "даст две параллельные строчки, а снизу зигзаг будет растягиваться "
                 "вместе с трикотажем." % hem_w)]
    if profile.zigzag:
        return [("Подшить зигзагом",
                 "Подогните припуск %.0f см на изнаночную сторону, заутюжьте. "
                 "Проложите зигзаг (ширина 3-4 мм) по сгибу, слегка растягивая ткань. "
                 "Лишний припуск обрежьте близко к строчке." % hem_w)]
    return [("Подшить вручную",
             "Подогните припуск %.0f см, приметайте. Подшейте потайным швом вручную: "
             "иглой захватывайте по одной-две нити ткани и петлю подогнутого края. "
             "Для трикотажа можно использовать простую прямую строчку в 1 см от сгиба, "
             "не растягивая ткань." % hem_w)]


