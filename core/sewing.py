def fabric_warning(knit: bool, profile: MachineProfile) -> str:
    if knit and not profile.zigzag and not profile.cover:
        return ("Вы шьёте трикотаж на прямострочной машине: обязательно поставьте "
                "иглу Jersey (№ 70-80) и используйте бельевой шов. Обычная прямая "
                "строчка не тянется — при растяжении она лопнет.")
    return ""
